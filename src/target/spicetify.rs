//! Spotify through spicetify: a `CrownOS` theme with a `crownos` color scheme.

use crate::environment::Environment;
use crate::error::TargetError;
use crate::target::Target;
use crate::theme::Theme;
use crate::util::{fs, process};

const COLORS: &str = include_str!("../../templates/spicetify.ini");
const USER_CSS: &str = "/* Generated by crownos-theme-engine; colors live in color.ini. */\n";
const THEME: &str = "CrownOS";
const SCHEME: &str = "crownos";

pub struct Spicetify;

impl Target for Spicetify {
    fn name(&self) -> &str {
        "spicetify"
    }

    fn is_installed(&self) -> bool {
        process::is_on_path("spicetify")
    }

    fn apply(&self, theme: &Theme, environment: &Environment) -> Result<(), TargetError> {
        let dir = environment.config_path(format!("spicetify/Themes/{THEME}"));
        let changed = fs::write_if_changed(&dir.join("color.ini"), &theme.render(COLORS)?)?;
        fs::write_if_changed(&dir.join("user.css"), USER_CSS)?;
        if !changed || !environment.runs_commands() {
            return Ok(());
        }
        process::run(
            "spicetify",
            [
                "config",
                "current_theme",
                THEME,
                "color_scheme",
                SCHEME,
                "inject_css",
                "1",
                "replace_colors",
                "1",
            ],
        )?;
        process::run("spicetify", ["refresh"]).or_else(|_| process::run("spicetify", ["apply"]))
    }
}
